def scene(time_steps, screen, flip=False, drift="#1a1210", span="4", sun="sun--morning", label="A drawing of the Desk"):
    """A pinned act: three steps beside one drawn screen."""
    steps = []
    cues = ['0 0.3 0 0.15', '0.28 0.62 0.15 0.15', '0.6']
    for (t, h, p), cue in zip(time_steps, cues):
        steps.append(f'''        <div class="step" data-sc-cue="{cue}">
          <p class="time">{t}</p>
          <h2 class="sc-display">{h}</h2>
          <p class="sc-body">{p}</p>
        </div>''')
    steps = "\n".join(steps)
    cls = "scene scene--flip" if flip else "scene"
    mac = f'''      <div class="mac" data-sc-tilt="4" aria-label="{label}">
        {MENUBAR}
        {screen}
      </div>'''
    body = (mac + "\n\n      <div class=\"steps\">\n" + steps + "\n      </div>") if flip else ("      <div class=\"steps\">\n" + steps + "\n      </div>\n\n" + mac)
    return f'''  <section data-sc-act="pin" data-sc-span="{span}" data-sc-drift="{drift}">
    <div data-sc-stage class="{cls}">
      <div class="sun {sun}" aria-hidden="true"></div>

{body}
    </div>
  </section>

'''


def rail(time, h2, p, cards, drift="#241812"):
    return f'''  <section data-sc-act="pan" data-sc-span="{2.2 + 0.55 * len(cards):.1f}" data-sc-drift="{drift}">
    <div data-sc-stage class="noon">
      <div class="sun sun--noon" aria-hidden="true"></div>
      <div class="rail" data-sc-pan="0.04">
        <div class="rail__lead sc-stack">
          <p class="time">{time}</p>
          <h2 class="sc-display sc-display--lg">{h2}</h2>
          <p class="sc-body">{p}</p>
        </div>
{"".join(cards)}      </div>
    </div>
  </section>

'''


def card(h3, p, rows, foot, more=False):
    cls = "card card--more" if more else "card"
    r = "\n".join(f'          <div class="row"><b>{a}</b><i>{b}</i></div>' for a, b in rows)
    return f'''        <div class="{cls}" data-sc-tilt="6">
          <h3>{h3}</h3>
          <p>{p}</p>
{r}
          <span class="card__foot">{foot}</span>
        </div>

'''


def yours(h2, items, drift="#0d0a0b"):
    its = "\n".join(f'        <div><b>{b}</b> {t}</div>' for b, t in items)
    return f'''  <section class="sc-section yours" data-sc-act="flow" data-sc-drift="{drift}">
    <div class="sc-wrap">
      <h2 class="sc-display sc-display--lg" data-sc-in>{h2}</h2>
      <div class="yours__grid" data-sc-in data-sc-stagger="70">
{its}
      </div>
    </div>
  </section>

'''


def msg(kind, text, cue=None, who=None):
    c = f' data-sc-cue="{cue}"' if cue else ""
    w = f"<small>{who}</small>" if who else ""
    return f'<p class="msg msg--{kind}"{c}>{w}{text}</p>'


def choices(items, cue=None):
    c = f' data-sc-cue="{cue}"' if cue else ""
    sp = "".join(f'<span class="go">{t}</span>' if i == 0 else f"<span>{t}</span>" for i, t in enumerate(items))
    return f'<div class="choices"{c}>{sp}</div>'


def local(text, cue=None):
    c = f' data-sc-cue="{cue}"' if cue else ""
    return f'<span class="local"{c}>{text}</span>'


